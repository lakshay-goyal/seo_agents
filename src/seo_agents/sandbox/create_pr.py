"""Open a dummy PR: fork the repo, add `.seo_agents/readme.md`, propose it.

Who shows up on GitHub?
- Commit author: "seo-agents-bot" (set with `git config` in step 5).
- PR author / contributor username: whoever owns GITHUB_TOKEN
  (check locally with `gh auth status`). GitHub resolves the
  fork/push/PR to that account no matter what `git config` says.
"""

import os

PR_TITLE = "chore(seo-agents): add dummy .seo_agents/readme.md"
PR_BRANCH = "seo-agents/dummy-pr"

PR_BODY = """\
## Dummy PR by seo-agents

This is an automated dummy PR created by the **seo-agents** pipeline to verify
fork → branch → commit → pull-request flow from inside a LangSmith sandbox.

No production code is changed. The only file added is `.seo_agents/readme.md`,
which describes the SEO services this agent provides.

- Branch: `seo-agents/dummy-pr`
- Safe to close/ignore — used for integration testing.
"""

GIT_USER_NAME = "seo-agents-bot"
GIT_USER_EMAIL = "seo-agents-bot@users.noreply.github.com"

README_CONTENT = """\
# SEO Agents — Services Overview

> Dummy file generated by the **seo-agents** pipeline (`create_pr`).
> Location: `.seo_agents/readme.md`. Safe to edit or delete.

## What we do

Automated SEO audits and fixes for web repositories, executed from an
isolated LangSmith sandbox after cloning the target GitHub repo.

## Services

### 1. On-page SEO
- Content arrangement and search-intent match per route template.
- Page structure: H1/H2/H3 hierarchy and semantic HTML.
- Internal links: anchor graph, descriptive anchors, orphan/deep pages.
- Metadata & social cards: unique titles, meta descriptions, canonical tags,
  robots meta, Open Graph / Twitter cards.
- Media & alt text: `<img>` / `<Image>` alt coverage, filenames, lazy-load,
  modern formats, transcripts.
- URL & information architecture: short hyphenated slugs, hub/subfolder
  grouping, depth, breadcrumbs.
- E-E-A-T & trust: author bylines, About/Contact/Privacy pages, testimonials,
  TOC/FAQ blocks, thin/duplicate boilerplate detection.

### 2. Technical SEO
- Crawlability & indexability baseline.
- Sitemap and `robots.txt` generation and validation.
- Canonicals, redirects, status codes, trailing-slash normalization.
- HTTPS, HSTS, CSP and security headers.
- Rendering strategy per route: SSR / SSG / ISR / CSR, hydration boundaries.
- Core Web Vitals: LCP < 2.5s, INP < 200ms, CLS < 0.1.
- Structured data: JSON-LD (Article, Product, Breadcrumb, FAQ, Organization,
  LocalBusiness) and visible-content match.
- Mobile parity: responsive layouts, same primary content, tap targets.
- Hreflang / i18n: locale routing, per-locale canonicals, localized sitemaps.

### 3. Off-page SEO readiness
- Linkable-asset inventory: blog, docs, tools, calculators, data, templates.
- Share plumbing: share buttons, embeds, RSS/Atom, UTM hooks.
- Brand/entity signals: Organization/Person schema, `sameAs` links.
- Local presence: NAP blocks, LocalBusiness schema, location pages.
- AI-search readiness: `llms.txt`, Markdown endpoints, FAQ/Q&A blocks.

## Pipeline stages

1. `validate` — check the GitHub URL.
2. `sandbox` — boot a LangSmith sandbox.
3. `clone` — `git clone` the repo into the sandbox.
4. `create_pr` (this file) — fork, add this README on a branch, open a PR.
5. `repo_analysis` — run on-page / technical / off-page exploration.
"""


def create_pr(sandbox, github_url):
    """Fork the repo, commit `.seo_agents/readme.md`, open a PR. Returns PR URL."""

    # 1. Split "https://github.com/<owner>/<repo>" into owner + repo.
    bits = github_url.strip().removesuffix("/").removesuffix(".git").split("/")
    owner, repo = bits[-2], bits[-1]
    target = f"/tmp/{repo}"  # same folder clone_repo() clones into

    # 2. Token for fork + push + PR (gh reads GH_TOKEN, git push reads GITHUB_TOKEN).
    token = os.environ.get("GITHUB_TOKEN")
    if not token:
        raise RuntimeError("Set GITHUB_TOKEN in .env first.")
    env = {"GITHUB_TOKEN": token, "GH_TOKEN": token}

    # 3. Shorthand: run a command in the sandbox, fail loudly if it errors.
    def run(cmd):
        result = sandbox.run(cmd, env=env)
        if not result.success:
            raise RuntimeError(f"FAILED: {cmd}\n{result.stdout}\n{result.stderr}")
        return result.stdout.strip()

    # 4. Make sure git + gh exist and the repo is cloned in the sandbox.
    run("git --version")
    run("gh --version || (apt-get update -qq && apt-get install -y -qq gh)")
    run(f"test -d {target}/.git || git clone {github_url} {target}")

    # 5. Fork the repo into your account (error = fork already exists, ignore it).
    sandbox.run(f"gh repo fork {owner}/{repo} --clone=false", env=env)
    fork_owner = run("gh api user -q .login")  # your GitHub username
    base = run(f"gh api repos/{owner}/{repo} -q .default_branch")  # e.g. "main"

    # 6. New branch, dummy README, commit as seo-agents-bot.
    run(f"cd {target} && git fetch origin -q && git checkout -B {PR_BRANCH} origin/{base}")
    run(f"cd {target} && git config user.name '{GIT_USER_NAME}' && git config user.email '{GIT_USER_EMAIL}'")
    sandbox.write(f"{target}/.seo_agents/readme.md", README_CONTENT)
    if run(f"cd {target} && git status --porcelain"):  # skip commit if nothing changed
        run(f"cd {target} && git add .seo_agents/readme.md && git commit -q -m '{PR_TITLE}'")

    # 7. Push the branch to YOUR fork (${GITHUB_TOKEN} comes from env, not the command).
    run(f"cd {target} && git push 'https://x-access-token:${{GITHUB_TOKEN}}@github.com/{fork_owner}/{repo}.git' {PR_BRANCH}")

    # 8. Open the PR — or return the existing one if you re-run this.
    sandbox.write("/tmp/seo_agents_pr_body.md", PR_BODY)
    already = run(f"gh pr list --repo {owner}/{repo} --head {fork_owner}:{PR_BRANCH} --json url -q '.[0].url'")
    if already and already != "null":
        print(f"PR already exists: {already}")
        return already
    pr_url = run(
        f"gh pr create --repo {owner}/{repo} --base {base} "
        f"--head {fork_owner}:{PR_BRANCH} --title '{PR_TITLE}' --body-file /tmp/seo_agents_pr_body.md"
    )
    print(f"Opened PR: {pr_url}")
    return pr_url
