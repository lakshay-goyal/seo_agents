"""Open the SEO exploration PR on the client repo.

Runs on the runner's machine (inside the sandbox container):
fork the client repo, commit seo_reports/site_model/**, repo_context.json and any
optional seo_reports/onpage/*.json reports plus a readme, push to the fork, open the PR.
"""

import json
import os
import re
import shlex

from seo_agents.repo_analysis.tools.repository.repository_constants import REPORT_FILES
from seo_agents.repo_analysis.agents.legacy_llm_extractors.report_contracts import validate_report
from seo_agents.utils.step_logger import done, log, start
from seo_agents.sandbox.github_url_validation import is_valid_github_url

PR_TITLE = "chore(seo-agents): SEO exploration summary"
PR_TITLE_PROPOSALS = "chore(seo-agents): SEO exploration summary and on-page proposals"
PR_BRANCH_PREFIX = "seo-agents/"
COMMIT_BUDGET = 50_000  # bytes of JSON committed to the client repo by default

PR_BODY = """\
## SEO exploration

Generated by seo-agents from commit `{sha}`. Only a compact summary is committed
({committed_count} files, {committed_kb} KB); the full exploration JSON ({excluded_count} more files,
{excluded_kb} KB) stays out of your production branch because it goes stale on the next content
commit. Re-run seo-agents (or set `SEO_PR_COMMIT_FULL=1`) for the complete model.

Each fact records how it was observed (`rendered` DOM, `raw` HTML or static `source`) and where
to change it (file, line, column and an edit scope such as literal, data, template, layout or shell).
No production code is changed.
{summary}"""

GIT_USER_NAME = "seo-agents-bot"
GIT_USER_EMAIL = "seo-agents-bot@users.noreply.github.com"

TMP_PATH = re.compile(r"(?:/private)?/tmp/[A-Za-z0-9._@+-]+(?:/[A-Za-z0-9._@+-]+)*")


def scrub_paths(text, roots=()):
    """Remove machine-local absolute paths (checkout dirs, /tmp) from anything committed."""
    for root in sorted({r.rstrip("/") for r in roots if r}, key=len, reverse=True):
        text = text.replace(root + "/", "").replace(root, ".")
    return TMP_PATH.sub("<tmp>", text)


def commit_priority(path):
    name = path.rsplit("/", 1)[-1]
    if name in {"manifest.json", "summary.json"}:
        return 0
    if path.startswith("seo_reports/onpage/") or path in {"seo_reports/keywords/keyword_map.json",
                                                          "seo_reports/keywords/summary.md",
                                                          "seo_reports/keywords/keyword_research.csv"}:
        return 1
    if name == "index.json":
        return 2
    return 3


def commit_plan(files, budget=None, full=None):
    """(committed, excluded) for {path: text}. Summary/manifest first, then on-page proposals, then the
    smallest remaining files while the byte budget lasts. full=True (SEO_PR_COMMIT_FULL=1) commits all."""
    full = os.environ.get("SEO_PR_COMMIT_FULL", "0") == "1" if full is None else full
    if full:
        return dict(files), {}
    budget = budget if budget is not None else int(os.environ.get("SEO_PR_COMMIT_BUDGET", str(COMMIT_BUDGET)))
    committed, excluded, used = {}, {}, 0
    for path in sorted(files, key=lambda p: (commit_priority(p), len(files[p].encode()), p)):
        size = len(files[path].encode())
        if commit_priority(path) == 0 or used + size <= budget:
            committed[path] = files[path]
            used += size
        else:
            excluded[path] = size
    return committed, excluded


def run_branch(sha=None, now=None):
    from datetime import datetime, timezone
    stamp = (now or datetime.now(timezone.utc)).strftime("%Y%m%d-%H%M")
    return PR_BRANCH_PREFIX + stamp + ("-" + sha[:7] if sha else "")


def summary_markdown(files, limit=15):
    """Best-effort human summary for the PR body from summary.json / index files."""
    lines = []
    for path in sorted(files):
        if not path.endswith("summary.json"):
            continue
        try:
            document = json.loads(files[path])
        except ValueError:
            continue
        issues = document.get("issues") if isinstance(document, dict) else None
        if isinstance(issues, list) and issues:
            lines.append("\n### Top issues (`" + path + "`)\n")
            for issue in issues[:limit]:
                if not isinstance(issue, dict):
                    continue
                label = issue.get("title") or issue.get("summary") or issue.get("id") or "issue"
                severity = issue.get("severity") or issue.get("impact") or ""
                scope = issue.get("scope") or ""
                fix = issue.get("fix") if isinstance(issue.get("fix"), dict) else {}
                where = fix.get("where") or fix.get("file") or ""
                lines.append("- " + (("**" + str(severity) + "** ") if severity else "") + str(label)
                             + ((" (" + str(scope) + ")") if scope else "") + ((" → `" + str(where) + "`") if where else ""))
    proposals = [p for p in files if p.startswith("seo_reports/onpage/") and p.endswith(".json")]
    if proposals:
        lines.append("\n### On-page proposals\n")
        lines.append("Review `seo_reports/onpage/` (" + str(len(proposals)) + " JSON files); apply only what you approve.")
    return "\n".join(lines)


def split_github_url(github_url):
    if not is_valid_github_url(github_url):
        raise ValueError("Not a valid GitHub repository URL: " + repr(github_url))
    from seo_agents.sandbox.git.repository_clone import owner_repo, repo_folder
    owner, repo = owner_repo(github_url)
    return owner, repo, repo_folder(github_url)


def login_env():
    token = os.environ.get("GITHUB_TOKEN")
    if not token:
        raise RuntimeError("Set GITHUB_TOKEN in .env first (classic PAT with the `repo` scope).")
    return {"GITHUB_TOKEN": token, "GH_TOKEN": token}


def check_reports(reports, *, require_any=True):
    """Validate whichever category reports exist; none are mandatory."""
    if reports is None:
        reports = {}
    if not isinstance(reports, dict):
        raise ValueError("PR publication requires an in-memory reports dictionary")
    unknown = sorted(set(reports) - set(REPORT_FILES))
    if unknown:
        raise ValueError("Unknown report categories: " + str(unknown))
    for category, report in reports.items():
        validate_report(category, report)
    if require_any and not reports:
        raise RuntimeError("Nothing to publish: no reports and no extra files")
    return reports


def run_or_fail(runner, env, command):
    result = runner.run(command, env=env)
    if not result.success:
        raise RuntimeError("FAILED: " + command + "\n" + result.stdout + result.stderr)
    return result.stdout.strip()


def safe_relative(relative):
    if not relative or relative.startswith("/") or ".." in relative.split("/") or "\0" in relative:
        raise ValueError("extra file path must stay inside the repository: " + repr(relative))
    return relative


def create_pr(runner, github_url, reports=None, extra_files=None, *, base_sha=None, summary=None, branch=None,
              excluded=None):
    """reports: optional {category: report}; extra_files: {repo-relative path: text} already selected for commit.
    base_sha: the analysed commit (the PR is based on it). Each run pushes its own branch; nothing is force-pushed."""
    begun = start("PR on " + github_url)
    owner, repo, target = split_github_url(github_url)
    extra_files = {safe_relative(path): content for path, content in (extra_files or {}).items()}
    reports = check_reports(reports, require_any=not extra_files)
    if base_sha is not None and not re.fullmatch(r"[0-9a-f]{40}", base_sha):
        raise ValueError("base_sha must be a full commit SHA")
    # Serialize every payload before any GitHub or filesystem mutation.
    payloads = {
        "seo_reports/onpage/" + REPORT_FILES[key]: json.dumps(report, indent=2, ensure_ascii=False, allow_nan=False) + "\n"
        for key, report in reports.items()
    }
    files = {path: scrub_paths(content, (target,)) for path, content in {**payloads, **extra_files}.items()}
    branch = branch or os.environ.get("SEO_PR_BRANCH") or run_branch(base_sha)
    if not re.fullmatch(r"[A-Za-z0-9._/-]+", branch) or ".." in branch:
        raise ValueError("Unsafe branch name: " + repr(branch))
    has_proposals = any(path.startswith("seo_reports/onpage/") for path in files)
    title = PR_TITLE_PROPOSALS if has_proposals else PR_TITLE
    excluded = excluded or {}
    body = PR_BODY.format(sha=(base_sha or "HEAD")[:12], committed_count=len(files),
                          committed_kb=round(sum(len(c.encode()) for c in files.values()) / 1024, 1),
                          excluded_count=len(excluded), excluded_kb=round(sum(excluded.values()) / 1024, 1),
                          summary=summary if summary is not None else summary_markdown(files))
    env = login_env()
    q = shlex.quote
    q_target = q(target)
    slug = q(owner + "/" + repo)
    log("target checkout: " + target)

    run_or_fail(runner, env, "git --version")
    run_or_fail(runner, env, "gh --version || (apt-get update -qq && apt-get install -y -qq gh)")
    run_or_fail(runner, env, "test -d " + q(target + "/.git") + " || git clone --depth 1 -- " + q(github_url) + " " + q_target)
    log("checkout ready: " + target)

    runner.run("gh repo fork " + slug + " --clone=false", env=env)
    fork_owner = run_or_fail(runner, env, "gh api user -q .login")
    base = run_or_fail(runner, env, "gh api " + q("repos/" + owner + "/" + repo) + " -q .default_branch")
    log("forked as " + fork_owner + ", base branch " + base)

    start_point = base_sha or ("origin/" + base)
    run_or_fail(runner, env, "cd " + q_target + " && git fetch origin -q && git checkout -B " + q(branch) + " " + q(start_point))
    run_or_fail(runner, env, "cd " + q_target + " && git config user.name " + q(GIT_USER_NAME) + " && git config user.email " + q(GIT_USER_EMAIL))
    log("branch ready: " + branch + " at " + start_point)

    added = []
    for relative, content in files.items():
        runner.write(target + "/" + relative, content)
        added.append(relative)
    log("staged " + str(len(added)) + " report files")
    run_or_fail(runner, env, "cd " + q_target + " && git add -- " + " ".join(q(path) for path in added))
    if run_or_fail(runner, env, "cd " + q_target + " && git status --porcelain"):
        run_or_fail(runner, env, "cd " + q_target + " && git commit -q -m " + q(title))
        log("committed " + str(len(added)) + " files")

    push_url = "https://x-access-token:${GITHUB_TOKEN}@github.com/" + fork_owner + "/" + repo + ".git"
    # Double quotes so bash expands only ${GITHUB_TOKEN}; owner/repo are validated identifiers.
    if not re.fullmatch(r"[A-Za-z0-9-]+", fork_owner):
        raise RuntimeError("Unexpected GitHub login: " + repr(fork_owner))
    run_or_fail(runner, env, "cd " + q_target + ' && git push "' + push_url + '" ' + q("HEAD:refs/heads/" + branch))
    log("pushed branch " + branch)

    head = branch if fork_owner == owner else fork_owner + ":" + branch
    already = run_or_fail(
        runner, env,
        "gh pr list --repo " + slug + " --head " + q(head) + " --json url -q " + q(".[0].url"),
    )
    if already and already != "null":
        log("PR already exists: " + already)
        done("PR on " + github_url, begun)
        return already
    pr_url = run_or_fail(
        runner, env,
        "gh pr create --repo " + slug + " --base " + q(base)
        + " --head " + q(head) + " --title " + q(title) + " --body " + q(body),
    )
    log("opened PR: " + pr_url)
    done("PR on " + github_url, begun)
    return pr_url


class PullRequestPublisher:
    """Tool: commit the compact report files on a per-run branch and open (or update) the reports PR."""

    def create(self, runner, github_url, reports=None, extra_files=None, *, base_sha=None, summary=None, branch=None,
               excluded=None):
        return create_pr(runner, github_url, reports, extra_files, base_sha=base_sha, summary=summary, branch=branch,
                         excluded=excluded)

    def commit_plan(self, files, budget=None, full=None):
        return commit_plan(files, budget, full)

    def summary_markdown(self, files, limit=15):
        return summary_markdown(files, limit)
